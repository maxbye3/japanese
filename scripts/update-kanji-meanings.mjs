import { readFile, writeFile } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';

const root = new URL('../', import.meta.url);
const signs = (await readFile(new URL('kanji.js', root), 'utf8')).split('const SIGNS = [')[1].split('].map')[0];
const phrases = await readFile(new URL('katakana.js', root), 'utf8');
const texts = [
  ...[...signs.matchAll(/^\s*\['([^']+)'/gm)].map((match) => match[1]),
  ...[...phrases.matchAll(/japanese: '([^']+)'/g)].map((match) => match[1]),
];
const needed = new Set(texts.join('').match(/[\u3400-\u4dbf\u4e00-\u9fff]/gu));
const source = 'https://www.edrdg.org/kanjidic/kanjidic2.xml.gz';
let compressed;
if (process.argv[2]) compressed = await readFile(process.argv[2]);
else {
  const response = await fetch(source);
  if (!response.ok) throw new Error('KANJIDIC2 download failed: ' + response.status);
  compressed = Buffer.from(await response.arrayBuffer());
}
const xml = gunzipSync(compressed).toString('utf8');
const entities = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" };
const decode = (value) => value.replace(/&(#x[0-9a-f]+|#\d+|amp|lt|gt|quot|apos);/gi, (_, entity) =>
  entity[0] === '#' ? String.fromCodePoint(entity[1] === 'x' ? parseInt(entity.slice(2), 16) : Number(entity.slice(1))) : entities[entity]);
const meanings = {};
for (const match of xml.matchAll(/<character>([\s\S]*?)<\/character>/g)) {
  const character = match[1].match(/<literal>(.*?)<\/literal>/)?.[1];
  if (!needed.has(character)) continue;
  const english = [...match[1].matchAll(/<meaning>(.*?)<\/meaning>/g)].map((entry) => decode(entry[1]));
  if (english.length) meanings[character] = english.slice(0, 4).join('; ');
}
const missing = [...needed].filter((character) => !meanings[character]);
if (missing.length) throw new Error('Missing character meanings: ' + missing.join(''));
const sorted = Object.fromEntries(Object.entries(meanings).sort(([a], [b]) => a.codePointAt(0) - b.codePointAt(0)));
const output = '// Generated by scripts/update-kanji-meanings.mjs; do not edit by hand.\n'
  + '// KANJIDIC2 subset: copyright Jim Breen and EDRDG, CC BY-SA 4.0.\n'
  + '// Source: ' + source + '\n'
  + '// Documentation and licence: https://www.edrdg.org/wiki/KANJIDIC_Project.html\n'
  + '// https://www.edrdg.org/edrdg/licence.html\n'
  + 'window.KANJI_MEANINGS = Object.freeze(' + JSON.stringify(sorted, null, 2) + ');\n';
await writeFile(new URL('kanji-meanings.js', root), output);
console.log('Updated meanings for all ' + needed.size + ' kanji in the sign and listening banks.');
